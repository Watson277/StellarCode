import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";

const source = await readFile(new URL("../src/features/activity/toolPresentation.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2020, target: ts.ScriptTarget.ES2020 } }).outputText;
const { compactText, toolTarget, toolFailure, toolResultSummary, toolDuration } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const t = (message, values = {}) => message.replace(/\{(\w+)\}/g, (_, key) => String(values[key]));
assert.equal(toolTarget({ path: "C:/project/README.md", content: "private content" }), "C:/project/README.md");
assert.equal(toolTarget({ command: ["git", "status"] }), "git status");
assert.equal(toolTarget({ query: "Python async" }), "Python async");
assert.equal(toolTarget({ token: "secret", content: "secret" }), "");
assert.equal(toolTarget(), "");
assert.equal(toolDuration("1422 ms"), "1.42 s");
assert.equal(toolDuration("0 ms"), "0 ms");
assert.equal(toolDuration(""), "");
assert.equal(toolFailure("execute_command", "ParserError: MissingTypename", t).title, "Command syntax error");
assert.equal(toolFailure("execute_command", "SyntaxError: invalid syntax", t).title, "Code syntax error");
assert.equal(toolFailure("read_file", "ParserError in contents", t).title, "Tool execution failed");
assert.equal(toolFailure("web_fetch", "HTTPStatusError: Client error '429 Too Many Requests'", t).title, "Service rate limit reached");
assert.equal(toolFailure("read_file", "failed at line 429", t).title, "Tool execution failed");
assert.equal(toolFailure("execute_command", "exit_code: 7\nstderr:\nfailure", t).title, "Command exited with code 7");
assert.equal(toolFailure("read_file", "FileNotFoundError", t).title, "File or directory not found");
assert.equal(toolFailure("execute_command", "CommandNotFoundException", t).title, "Command not available");
assert.equal(toolResultSummary("running", '{"path":"secret"}', t), "Operation in progress");
assert.equal(toolResultSummary("completed", "exit_code: 0\nstdout:\nWorking tree clean", t), "Working tree clean");
assert.equal(toolResultSummary("completed", "exit_code: 0", t), "Command completed with no output");
assert.equal(toolResultSummary("completed", '{"results":[{},{}]}', t), "Returned 2 items");
assert.equal(toolResultSummary("completed", '{"other":true}', t), "Returned structured data");
assert.equal(toolResultSummary("completed", '{"content":[{"type":"text","text":"Weather: clear"}]}', t), "Weather: clear");
assert.equal(toolResultSummary("completed", "SyntaxError example in a file", t), "SyntaxError example in a file");
assert.equal(compactText("x".repeat(500)).length, 140);
console.log("Tool card presentation: all assertions passed");
