export function translate(
  language: Language,
  message: string,
  values: TranslationValues = {},
): string {
  const template = language === "zh-CN" ? ZH_CN[message] ?? message : message;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

export function translator(language: Language): Translator {
  return (message, values) => translate(language, message, values);
}

/** Translate diagnostics lifecycle/provider text owned by StellarCode.
 * Compiler and linter diagnostic bodies are intentionally not passed here.
 */
export function translateDiagnosticRuntimeText(language: Language, message: string): string {
  if (language === "en" || !message) return message;
  const dynamicPatterns: Array<{
    pattern: RegExp;
    key: string;
    values: (match: RegExpMatchArray) => TranslationValues;
  }> = [
    {
      pattern: /^Checking Python syntax in (\d+) file\(s\)\.\.\.$/,
      key: "Checking Python syntax in {count} file(s)...",
      values: (match) => ({ count: match[1] }),
    },
    {
      pattern: /^Diagnostics completed with (\d+) problem\(s\)\.$/,
      key: "Diagnostics completed with {count} problem(s).",
      values: (match) => ({ count: match[1] }),
    },
    {
      pattern: /^Python syntax: (\d+)\/(\d+)$/,
      key: "Python syntax: {current}/{total}",
      values: (match) => ({ current: match[1], total: match[2] }),
    },
    {
      pattern: /^Ruff: batch (\d+)\/(\d+)$/,
      key: "Ruff: batch {current}/{total}",
      values: (match) => ({ current: match[1], total: match[2] }),
    },
    {
      pattern: /^Python LSP: opened (\d+)\/(\d+) file\(s\)\.\.\.$/,
      key: "Python LSP: opened {current}/{total} file(s)...",
      values: (match) => ({ current: match[1], total: match[2] }),
    },
    {
      pattern: /^Python LSP analyzed (\d+) file\(s\)\.$/,
      key: "Python LSP analyzed {count} file(s).",
      values: (match) => ({ count: match[1] }),
    },
    {
      pattern: /^Python LSP opened (\d+) file\(s\), but the server did not publish diagnostics before the bounded wait ended\.$/,
      key: "Python LSP opened {count} file(s), but the server did not publish diagnostics before the bounded wait ended.",
      values: (match) => ({ count: match[1] }),
    },
    {
      pattern: /^TypeScript: (.+)$/,
      key: "TypeScript: {path}",
      values: (match) => ({ path: match[1] }),
    },
    {
      pattern: /^Cargo: (.+)$/,
      key: "Cargo: {path}",
      values: (match) => ({ path: match[1] }),
    },
  ];
  for (const entry of dynamicPatterns) {
    const match = message.match(entry.pattern);
    if (match) return translate(language, entry.key, entry.values(match));
  }
  return translate(language, message);
}

